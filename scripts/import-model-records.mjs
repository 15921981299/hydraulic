/**
 * Batch-import model records from a CSV into src/data/imported-model-records.ts.
 *
 * CSV columns:
 *   brand, model, productType, series,
 *   status, price, condition, leadTime, materialNumber
 *
 * Run: node scripts/import-model-records.mjs <path-to.csv>
 * Generates a TypeScript module that is consumed by src/data/model-records.ts.
 */
import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";

const csvPath = process.argv[2];
if (!csvPath) {
  console.error("Usage: node scripts/import-model-records.mjs <path-to.csv>");
  process.exit(1);
}

function slugify(value) {
  const slug = String(value)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 90);
  return slug || `record-${Math.random().toString(36).slice(2, 8)}`;
}

function parseCsv(text) {
  const lines = text
    .replace(/^\uFEFF/, "")
    .split(/\r?\n/)
    .filter((line) => line.trim());
  const parseLine = (line) => {
    const cells = [];
    let current = "";
    let inQuotes = false;
    for (let i = 0; i < line.length; i++) {
      const ch = line[i];
      if (inQuotes) {
        if (ch === '"' && line[i + 1] === '"') {
          current += '"';
          i++;
        } else if (ch === '"') {
          inQuotes = false;
        } else {
          current += ch;
        }
      } else if (ch === '"') {
        inQuotes = true;
      } else if (ch === ",") {
        cells.push(current.trim());
        current = "";
      } else {
        current += ch;
      }
    }
    cells.push(current.trim());
    return cells;
  };
  const header = parseLine(lines[0]);
  return lines.slice(1).map((line) => {
    const cells = parseLine(line);
    const row = {};
    header.forEach((h, i) => (row[h] = cells[i] ?? ""));
    return row;
  });
}

const csv = await readFile(csvPath, "utf8");
const rows = parseCsv(csv);

const required = [
  "brand",
  "model",
  "productType",
  "series",
];
const errors = [];
const slugs = new Set();
for (const [i, row] of rows.entries()) {
  const label = `row ${i + 2}`;
  for (const key of required) {
    if (!row[key]) errors.push(`${label}: missing ${key}`);
  }
  const slug = slugify(row.slug || row.model);
  if (slugs.has(slug)) errors.push(`${label}: duplicate model ${row.model}`);
  slugs.add(slug);
}
if (errors.length) {
  console.error(`Import rejected with ${errors.length} issue(s):`);
  for (const e of errors) console.error(`- ${e}`);
  process.exit(1);
}

const code = `// Generated by scripts/import-model-records.mjs from ${path.basename(
  csvPath,
)}. Do not edit by hand.
import { catalogRecord } from "./model-records.ts";

export const importedModelRecords = [
${rows
  .map(
    (row) => `  catalogRecord({
    slug: ${JSON.stringify(slugify(row.slug || row.model))},
    brand: ${JSON.stringify(row.brand)},
    model: ${JSON.stringify(row.model)},
    ${row.materialNumber ? `materialNumber: ${JSON.stringify(row.materialNumber)},` : ""}
    productType: ${JSON.stringify(row.productType)},
    series: ${JSON.stringify(row.series)},
    image: ${JSON.stringify(row.image || "/images/hydraulic/hydraulic-pumps.webp")},
    status: ${JSON.stringify(row.status || "Reconfirm")},
    ${row.price ? `price: ${JSON.stringify(row.price)},` : ""}
    condition: ${JSON.stringify(row.condition || "As stated on approved quotation")},
    leadTime: ${JSON.stringify(row.leadTime || "Reconfirm against current stock")},
  }),`,
  )
  .join("\n")}
];
`;

await mkdir("src/data", { recursive: true });
await writeFile("src/data/imported-model-records.ts", code, "utf8");
console.log(
  `Imported ${rows.length} model records into src/data/imported-model-records.ts`,
);
